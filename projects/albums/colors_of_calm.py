"""Colors of Calm - the noise-colour album for /zen (DistroKid release).

The /zen catalogue had one noise album (White Noise Therapy) and no pink,
grey, green or brown noise at all, while the site's most specific sound post
is brown-vs-white noise. Every track here is generated by `core.soundbed`, so
the audio is ours on every platform and each track's spectrum is a measured
fact the album page can print, not a mood word.

Six tracks, each a different colour, ordered bright to dark so the album
plays as a slow descent:

| # | track        | colour                                  |
|---|--------------|-----------------------------------------|
| 1 | Silver Veil  | white, softened above 12 kHz            |
| 2 | Rose Haze    | pink (equal energy per octave)          |
| 3 | Grey Balance | grey (inverse A-weighting: evenly loud) |
| 4 | Green Meadow | green (mid band, 120 Hz-2.2 kHz)        |
| 5 | Deep Brown   | brown (-6 dB per octave)                |
| 6 | Velvet Night | brown, rolled off above 500 Hz, for sleep |

Mastering: every track at the same integrated loudness as the existing
catalogue (Cloudscape Serenity measured -17.7 LUFS) unless that would push
the sample peak past -1.5 dBFS - the brown tracks stop short of -18 for that
reason, rather than being limited. 3 s fades, 44.1 kHz
16-bit WAV for DistroKid. `--drift` adds a very slow random level wander
(about +-1.5 dB over 30-90 s) so ten minutes of noise feels less static; it is
the open audition question, so previews render Rose Haze both ways.

Run from the repo root:

    PYTHONPATH=. .venv/bin/python projects/albums/colors_of_calm.py --preview
    PYTHONPATH=. .venv/bin/python projects/albums/colors_of_calm.py --final

No copy about what this masks is written until `band_energy` has been read
for every track (printed at the end of each run).
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import butter, sosfilt

from video_automation.core import soundbed
from video_automation.core.soundbed import SR, Bed

OUT = Path("~/Desktop/colors-of-calm").expanduser()
TARGET_LUFS = -18.0
PEAK_CEILING_DB = -1.5   # sample peak; brown would otherwise clip at -18 LUFS
FADE = 3.0


@dataclass(frozen=True)
class Track:
    n: int
    title: str
    bed: Bed | None          # None means a custom generator below (grey)
    seed: int


TRACKS = [
    Track(1, "Silver Veil", Bed("white", tilt_hz=12000), 11),
    Track(2, "Rose Haze", Bed("pink"), 23),
    Track(3, "Grey Balance", None, 37),
    Track(4, "Green Meadow", Bed("green"), 41),
    Track(5, "Deep Brown", Bed("brown"), 53),
    Track(6, "Velvet Night", Bed("brown", tilt_hz=500), 67),
]


def _a_weight_db(f: np.ndarray) -> np.ndarray:
    f2 = np.maximum(f, 1e-3) ** 2
    ra = (12194.0 ** 2 * f2 ** 2) / (
        (f2 + 20.6 ** 2)
        * np.sqrt((f2 + 107.7 ** 2) * (f2 + 737.9 ** 2))
        * (f2 + 12194.0 ** 2))
    return 20 * np.log10(ra) + 2.0


def grey(duration: float, seed: int) -> np.ndarray:
    """White noise shaped by inverse A-weighting, so every band sounds about
    equally loud. The boost is capped at +15 dB (bass) and the top is not
    lifted above flat, or the low end turns to rumble and the highs to hiss."""
    n = int(duration * SR)
    f = np.fft.rfftfreq(n, 1 / SR)
    gain_db = np.clip(-_a_weight_db(f), -3.0, 15.0)
    gain_db[f > 10000] = np.minimum(gain_db[f > 10000], 0.0)
    gain = 10 ** (gain_db / 20)
    gain[f < 20] = 0.0
    chans = []
    for ch in range(2):
        w = np.random.default_rng(seed + ch * 977).normal(0, 1, n)
        chans.append(np.fft.irfft(np.fft.rfft(w) * gain, n).astype(np.float32))
    x = np.stack(chans, axis=1)
    return x / np.max(np.abs(x)) * 0.9


def drift_env(n: int, seed: int, depth_db: float = 1.5) -> np.ndarray:
    """Slow random level wander: noise lowpassed to ~1/45 Hz, scaled to
    +-depth_db. Generated at 10 Hz and interpolated, since a 0.02 Hz filter at
    48 kHz is numerically useless."""
    rate = 10
    m = n // (SR // rate) + 2
    r = np.random.default_rng(seed + 5000).normal(0, 1, m + rate * 600)
    sos = butter(2, 1 / 45, btype="low", fs=rate, output="sos")
    r = sosfilt(sos, r)[rate * 600:]
    r = r / (np.max(np.abs(r)) or 1.0) * depth_db
    env_db = np.interp(np.arange(n) / SR, np.arange(m) / rate, r)
    return (10 ** (env_db / 20)).astype(np.float32)


def make(track: Track, duration: float, drift: bool) -> np.ndarray:
    x = (grey(duration, track.seed) if track.bed is None
         else soundbed.render(duration, track.bed, seed=track.seed))
    if track.bed is not None and track.bed.colour == "brown":
        # Below 25 Hz is inaudible on most headphones but eats the headroom
        # loudness normalisation needs, since LUFS barely counts it.
        sos = butter(2, 25.0, btype="high", fs=SR, output="sos")
        x = sosfilt(sos, x, axis=0).astype(np.float32)
    if drift:
        x = x * drift_env(len(x), track.seed)[:, None]
    k = int(FADE * SR)
    ramp = np.sin(np.linspace(0, np.pi / 2, k, dtype=np.float32)) ** 2
    x[:k] *= ramp[:, None]
    x[-k:] *= ramp[::-1][:, None]
    return x


def lufs(path: Path) -> tuple[float, float]:
    """(integrated LUFS, true peak dBTP) via ffmpeg's ebur128."""
    err = subprocess.run(
        ["ffmpeg", "-hide_banner", "-nostats", "-i", str(path),
         "-af", "ebur128=peak=true", "-f", "null", "-"],
        capture_output=True, text=True).stderr
    i = float(re.findall(r"I:\s+(-?[\d.]+) LUFS", err)[-1])
    tp = float(re.findall(r"Peak:\s+(-?[\d.]+) dBFS", err)[-1])
    return i, tp


def master(x: np.ndarray, out: Path, mp3: bool) -> dict:
    """Gain to TARGET_LUFS (noise is stationary, so one measured gain lands
    within a tenth of a dB), then encode to 44.1 kHz."""
    out.parent.mkdir(parents=True, exist_ok=True)
    raw = out.with_suffix(".raw.wav")
    sf.write(str(raw), x, SR, subtype="FLOAT")
    i, _ = lufs(raw)
    gain = min(10 ** ((TARGET_LUFS - i) / 20),
               10 ** (PEAK_CEILING_DB / 20) / float(np.max(np.abs(x))))
    sf.write(str(raw), x * gain, SR, subtype="FLOAT")
    codec = (["-c:a", "libmp3lame", "-b:a", "320k"] if mp3
             else ["-c:a", "pcm_s16le", "-af", "aresample=44100:dither_method=triangular"])
    ar = ["-ar", "44100"] if mp3 else []
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                    "-i", str(raw), *ar, *codec, str(out)], check=True)
    raw.unlink()
    i2, tp = lufs(out)
    band = soundbed.band_energy(x[int(30 * SR):])  # skip the fade-in
    return {"file": out.name, "lufs": round(i2, 1), "true_peak": round(tp, 1),
            **{k: round(v, 1) for k, v in band.items()}}


def main() -> None:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--preview", action="store_true",
                      help="2-minute MP3s, Rose Haze steady and drifting")
    mode.add_argument("--final", action="store_true",
                      help="10-minute 16-bit WAVs for DistroKid")
    ap.add_argument("--drift", action="store_true",
                    help="final only: apply the slow level wander to every track")
    ap.add_argument("--minutes", type=float, default=10.0)
    a = ap.parse_args()

    rows = []
    if a.preview:
        d = 120.0
        for t in TRACKS:
            rows.append(master(make(t, d, False),
                               OUT / "previews" / f"{t.n:02d} {t.title}.mp3", True))
        rose = TRACKS[1]
        rows.append(master(make(rose, d, True),
                           OUT / "previews" / f"{rose.n:02d} {rose.title} (drifting).mp3", True))
    else:
        d = a.minutes * 60
        for t in TRACKS:
            rows.append(master(make(t, d, a.drift),
                               OUT / "final" / f"{t.n:02d} {t.title}.wav", False))

    print(json.dumps(rows, indent=1))
    (OUT / ("previews" if a.preview else "final") / "measurements.json").write_text(
        json.dumps(rows, indent=1))


if __name__ == "__main__":
    main()
